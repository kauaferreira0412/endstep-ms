create table formats (
    code                  varchar(32) primary key,
    name                  varchar(64)  not null,
    min_deck              integer,
    max_deck              integer,
    max_copies            integer      not null default 4,
    singleton             boolean      not null default false,
    uses_command_zone     boolean      not null default false,
    default_life          integer      not null default 20,
    enforce_color_identity boolean     not null default false,
    sideboard_max         integer      not null default 15,
    sort_order            integer      not null default 100
);
create index idx_formats_name       on formats (name);
create index idx_formats_min_deck   on formats (min_deck);
create index idx_formats_max_deck   on formats (max_deck);
create index idx_formats_max_copies on formats (max_copies);
create index idx_formats_singleton  on formats (singleton);
create index idx_formats_uses_cz    on formats (uses_command_zone);
create index idx_formats_life       on formats (default_life);
create index idx_formats_color_id   on formats (enforce_color_identity);
create index idx_formats_sb_max     on formats (sideboard_max);
create index idx_formats_sort_order on formats (sort_order);

