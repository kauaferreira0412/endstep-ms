create table games (
    id            bigint generated by default as identity primary key,
    room_id       bigint      not null references rooms (id) on delete cascade,
    format        varchar(32) not null references formats (code),
    status        varchar(16) not null default 'ACTIVE',
    turn_number   integer     not null default 1,
    active_seat   integer     not null default 0,
    phase         varchar(16) not null default 'UNTAP',
    last_sequence bigint      not null default 0,
    created_by    bigint      not null references users (id) on delete cascade,
    created_at    timestamptz not null default now(),
    started_at    timestamptz,
    finished_at   timestamptz,
    updated_at    timestamptz not null default now()
);
create index idx_games_room_id       on games (room_id);
create index idx_games_format        on games (format);
create index idx_games_status        on games (status);
create index idx_games_turn_number   on games (turn_number);
create index idx_games_active_seat   on games (active_seat);
create index idx_games_phase         on games (phase);
create index idx_games_last_sequence on games (last_sequence);
create index idx_games_created_by    on games (created_by);
create index idx_games_created_at    on games (created_at);
create index idx_games_started_at    on games (started_at);
create index idx_games_finished_at   on games (finished_at);
create index idx_games_updated_at    on games (updated_at);

alter table rooms add constraint fk_rooms_current_game
    foreign key (current_game_id) references games (id) on delete set null;

