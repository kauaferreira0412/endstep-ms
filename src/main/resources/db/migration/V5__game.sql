create table rooms (
    id               bigint generated by default as identity primary key,
    room_code        varchar(12)  not null unique,
    host_user_id     bigint       not null references users (id) on delete cascade,
    name             varchar(120) not null,
    format           varchar(32)  not null references formats (code),
    max_players      integer      not null default 4 check (max_players between 2 and 6),
    password_hash    varchar(100),
    visibility       varchar(16)  not null default 'PRIVATE',
    allow_spectators boolean      not null default true,
    status           varchar(16)  not null default 'OPEN',
    current_game_id  bigint,
    created_at       timestamptz  not null default now(),
    updated_at       timestamptz  not null default now()
);
create index idx_rooms_room_code       on rooms (room_code);
create index idx_rooms_host_user_id    on rooms (host_user_id);
create index idx_rooms_name            on rooms using gin (name gin_trgm_ops);
create index idx_rooms_format          on rooms (format);
create index idx_rooms_max_players     on rooms (max_players);
create index idx_rooms_password_hash   on rooms (password_hash);
create index idx_rooms_visibility      on rooms (visibility);
create index idx_rooms_allow_spectators on rooms (allow_spectators);
create index idx_rooms_status          on rooms (status);
create index idx_rooms_current_game_id on rooms (current_game_id);
create index idx_rooms_created_at      on rooms (created_at);
create index idx_rooms_updated_at      on rooms (updated_at);

create table room_players (
    id         bigint generated by default as identity primary key,
    room_id    bigint      not null references rooms (id) on delete cascade,
    user_id    bigint      not null references users (id) on delete cascade,
    role       varchar(16) not null default 'PLAYER',
    deck_id    bigint      references decks (id) on delete set null,
    seat       integer,
    status     varchar(16) not null default 'JOINED',
    joined_at  timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (room_id, user_id)
